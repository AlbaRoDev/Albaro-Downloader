// Mirrors `AppError` in src-tauri/src/errors.rs. `code` drives the UI text; `message` is the
// raw detail. Commands reject with it and `download-failed` carries it.
export const ERROR_CODES = [
  "network",
  "extractorBroken",
  "unavailable",
  "noSpace",
  "ffmpeg",
  "jsRuntimeMissing",
  "cancelled",
  "invalidUrl",
  "loginRequired",
  "unsupportedUrl",
  "alreadyQueued",
  "folderUnavailable",
  "cookiesUnavailable",
  "playlist",
  "unknown",
] as const;

export type ErrorCode = (typeof ERROR_CODES)[number];

export interface AppError {
  code: ErrorCode;
  message: string;
}

// What a rejected command gave, as an `AppError`. Commands reject with one, but Tauri rejects a
// bad argument with a plain string before the command runs (seen in practice), and anything
// else that throws is not one either: those become `unknown`, keeping their text.
export function asAppError(error: unknown): AppError {
  const e = error as Partial<AppError> | null;
  if (
    typeof e?.message === "string" &&
    (ERROR_CODES as readonly unknown[]).includes(e.code)
  ) {
    return { code: e.code as ErrorCode, message: e.message };
  }
  return { code: "unknown", message: String(error) };
}

// Mirrors `Progress` in src-tauri/src/ytdlp/progress.rs: one update for one file. A
// video+audio download sends two files in a row, each from 0 to 100 %.
export interface Progress {
  status: "downloading" | "finished" | "error";
  downloadedBytes: number | null;
  // Exact size, or yt-dlp's estimate in fragmented downloads (it jumps around).
  totalBytes: number | null;
  speed: number | null; // bytes per second
  eta: number | null; // seconds
  filename: string | null;
  fragmentIndex: number | null;
  fragmentCount: number | null;
}

// Mirrors `Metadata` and `Format` in src-tauri/src/ytdlp/metadata.rs.
export interface Metadata {
  id: string;
  title: string;
  channel: string | null;
  duration: number | null; // seconds; null for live streams
  thumbnail: string | null;
  webpageUrl: string;
  extractor: string;
  isLive: boolean | null; // null: the site did not say
  formats: Format[];
  // The languages it has subtitles in, by code, with no live chat.
  subtitleLanguages: SubtitleLanguage[];
}

// `manual`: written by a person; `auto`: generated by the site; both can be true (yt-dlp prefers
// the manual ones). `name` is the site's name for the language, which not every site gives.
export interface SubtitleLanguage {
  code: string;
  name: string | null;
  manual: boolean;
  auto: boolean;
}

export interface Format {
  formatId: string;
  ext: string;
  // "none" means no video (or audio); null means yt-dlp does not know.
  vcodec: string | null;
  acodec: string | null;
  height: number | null;
  width: number | null;
  fps: number | null;
  tbr: number | null; // kbit/s
  abr: number | null;
  vbr: number | null;
  filesize: number | null; // bytes, exact or estimated; HLS formats have none
  formatNote: string | null;
  protocol: string | null;
}

// Rejects with `playlist` when the link is a playlist or channel: list it with `fetchPlaylist`.
export function fetchMetadata(url: string): Promise<Metadata> {
  return invoke("fetch_metadata", { url });
}

// Mirrors `Playlist` and `PlaylistEntry` in src-tauri/src/ytdlp/playlist.rs.
export interface Playlist {
  title: string | null;
  channel: string | null;
  // In yt-dlp's order. A channel's tabs (Videos, Shorts...) come flattened into one list. At
  // most 5000.
  entries: PlaylistEntry[];
  // The list had more entries than that; the rest were not read.
  truncated: boolean;
}

export interface PlaylistEntry {
  url: string; // the video's own link
  title: string | null; // null for an unavailable video
  // Why it cannot be downloaded, if the listing already says so: such an entry has no
  // title, duration, thumbnail or channel, and the picker does not let it be ticked.
  unavailable: "private" | "deleted" | null;
  duration: number | null; // seconds
  thumbnail: string | null;
  channel: string | null;
}

// Every entry of the playlist or channel at `url`, without resolving the videos (fast).
export function fetchPlaylist(url: string): Promise<Playlist> {
  return invoke("fetch_playlist", { url });
}

