// Mirrors `DownloadRequest` and `Mode` in src-tauri/src/ytdlp/formats.rs. There is no
// output folder: the frontend never touches the file system.
export interface DownloadRequest {
  url: string;
  mode: Mode;
  // Set when the download is one entry of a playlist: it numbers the file and, in
  // audio mode, the track tag. Left out for a plain download.
  playlist?: PlaylistPosition;
  // A subfolder of the output folder for the file (the playlist's title). The backend
  // cleans it (characters a folder cannot have, length); nothing usable left means no subfolder.
  folder?: string;
  // Subtitles to embed in a video; ignored in audio mode. Left out for none.
  subtitles?: Subtitles;
}

// The language codes to embed and whether the automatic captions may be used for them (a
// language with no manual subtitles). A language the video lacks is skipped, not an error.
export interface Subtitles {
  langs: string[];
  auto: boolean;
}

// `index` starts at 1; `count` is the playlist's size (how many digits the number gets).
export interface PlaylistPosition {
  index: number;
  count: number;
}

export type Mode =
  // maxHeight null: no limit. container null: yt-dlp picks one that fits the codecs.
  | { kind: "video"; maxHeight: number | null; container: Container | null }
  // bitrateKbps only applies to mp3, m4a and opus.
  | { kind: "audio"; format: AudioFormat; bitrateKbps: number | null };

// "mp4" is the best resolution in an mp4 (AV1 up to 4K); "mp4Compatible" prefers H.264 + AAC,
// which plays everywhere (YouTube: up to 1080p). Neither re-encodes.
export type Container = "mp4" | "mp4Compatible" | "mkv" | "webm";

// "best" keeps the original audio, not re-encoded.
export type AudioFormat = "best" | "mp3" | "m4a" | "opus" | "flac" | "wav";

// Queue commands. Each rejects with an `AppError` if the state change is not
// allowed (for example, retrying a download that did not fail).

// Mirrors `DownloadState` in src-tauri/src/db.rs.
export type DownloadState =
  | "pending"
  | "active"
  | "paused"
  | "finished"
  | "failed"
  | "cancelled";

// Mirrors `Download` in src-tauri/src/db.rs: one row of the queue. Progress is not stored;
// it only arrives in `download-progress` events.
export interface Download {
  id: number;
  request: DownloadRequest;
  // From the preview, for the list. null for downloads queued before titles were stored.
  title: string | null;
  thumbnail: string | null;
  state: DownloadState;
  error: AppError | null; // the last error, if any
  createdAt: number; // ms since the Unix epoch
  updatedAt: number;
  // The playlist batch it was queued with, or null for a download on its own.
  batch: Batch | null;
}

// The entries chosen from one playlist and queued together: the list shows them as a group.
export interface Batch {
  id: number;
  title: string | null; // the playlist's
}

// What the list shows about a download besides its request (the preview's metadata). It takes no
// part in telling duplicates.
export interface DownloadInfo {
  title: string | null;
  thumbnail: string | null;
}

// Queues the download; it starts when there is a free slot. Resolves with its id. Rejects with
// `alreadyQueued` if the same request is pending, active or paused.
export function enqueueDownload(
  request: DownloadRequest,
  info?: DownloadInfo,
): Promise<number> {
  return invoke("enqueue_download", { request, info });
}

export interface NewDownload {
  request: DownloadRequest;
  info?: DownloadInfo;
}

// What a batch did: `skipped` were already pending, active or paused.
export interface Enqueued {
  queued: number;
  skipped: number;
}

// Queues many downloads at once, in order (the selected entries of a playlist). Those
// already in the queue are skipped, not errors. Any other error stops the batch: what was queued
// before it stays. `batchTitle` (the playlist's) names the group they are shown in.
export function enqueueDownloads(
  items: NewDownload[],
  batchTitle?: string | null,
): Promise<Enqueued> {
  return invoke("enqueue_downloads", { items, batchTitle });
}

