// Event payloads mirror `ProgressEvent`, `StateEvent`, `FinishedEvent`, `FailedEvent` and
// `RetryingEvent` in src-tauri/src/queue.rs. Several downloads run at once, so each carries
// its id. Every state change sends `download-state`; `download-finished` and
// `download-failed` follow it for those two outcomes. A cancellation is not a failure: it
// sends only `download-state` ("cancelled").
export interface ProgressEvent {
  id: number;
  progress: Progress;
}

// `error` is the one stored with the row: set for "failed", and for "pending" while a
// network retry waits.
export interface StateEvent {
  id: number;
  state: DownloadState;
  error: AppError | null;
}

// A network retry was scheduled: attempt `attempt` of `maxAttempts` starts in `delayMs`.
export interface RetryingEvent {
  id: number;
  attempt: number;
  maxAttempts: number;
  delayMs: number;
}

export interface FinishedEvent {
  id: number;
}

export interface FailedEvent {
  id: number;
  error: AppError;
}

export function onDownloadProgress(
  cb: (event: ProgressEvent) => void,
): Promise<UnlistenFn> {
  return listen<ProgressEvent>("download-progress", (e) => cb(e.payload));
}

export function onDownloadFinished(
  cb: (event: FinishedEvent) => void,
): Promise<UnlistenFn> {
  return listen<FinishedEvent>("download-finished", (e) => cb(e.payload));
}

export function onDownloadFailed(
  cb: (event: FailedEvent) => void,
): Promise<UnlistenFn> {
  return listen<FailedEvent>("download-failed", (e) => cb(e.payload));
}

export function onDownloadState(
  cb: (event: StateEvent) => void,
): Promise<UnlistenFn> {
  return listen<StateEvent>("download-state", (e) => cb(e.payload));
}

export function onDownloadRetrying(
  cb: (event: RetryingEvent) => void,
): Promise<UnlistenFn> {
  return listen<RetryingEvent>("download-retrying", (e) => cb(e.payload));
}

// The progress shown on the app's icon in the taskbar (Windows; each system treats it in its own
// way): nothing, a bar from 0 to 100, or the moving one for "working, no number yet".
export type TaskbarProgress =
  | { status: "none" }
  | { status: "normal"; progress: number }
  | { status: "indeterminate" };

// Needs the `core:window:allow-set-progress-bar` permission (capabilities/default.json), which
// is not part of `core:default`. Does nothing without a backend (a plain browser or a test).
export function setTaskbarProgress(state: TaskbarProgress): Promise<void> {
  if (!isBackendAvailable()) return Promise.resolve();
  const window = getCurrentWindow();
  switch (state.status) {
    case "none":
      return window.setProgressBar({ status: ProgressBarStatus.None });
    case "normal":
      return window.setProgressBar({
        status: ProgressBarStatus.Normal,
        progress: state.progress,
      });
    case "indeterminate":
      return window.setProgressBar({ status: ProgressBarStatus.Indeterminate });
  }
}

// True in the Tauri app, and in `pnpm dev` once ipc.mock.ts is installed: both define the
// internal `invoke` that every wrapper here goes through. False in a plain browser or test.
export function isBackendAvailable(): boolean {
  const internals = (window as { __TAURI_INTERNALS__?: { invoke?: unknown } })
    .__TAURI_INTERNALS__;
  return typeof internals?.invoke === "function";
}
