// Reads one video's metadata with `yt-dlp --dump-single-json`. A playlist is refused with
// `playlist` (listed by playlist.rs) and picking formats is formats.rs: this only returns what
// yt-dlp says, typed.
use std::{collections::BTreeMap, path::Path, time::Duration};

use serde::{Deserialize, Serialize};
use tauri::AppHandle;

use super::{
    check_url, classify, formats::is_language_code, js_runtime, runner::RunEvent, Cookies,
};
use crate::{
    errors::AppError,
    text::{self, LABEL_MAX, NAME_MAX, TITLE_MAX},
};

/// Read from yt-dlp's snake_case JSON and sent to the frontend in camelCase (mirrored by
/// `Metadata` in ipc.ts). Unknown fields are ignored. Required fields are the ones without
/// which the result is useless and that yt-dlp fills in itself for every site; the rest are
/// `Option`, because one missing required field fails the whole analysis.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all(serialize = "camelCase", deserialize = "snake_case"))]
pub struct Metadata {
    pub id: String,
    pub title: String,
    /// `channel` on YouTube; other sites (SoundCloud, Reddit) only fill `uploader`.
    pub channel: Option<String>,
    #[serde(skip_serializing)]
    uploader: Option<String>,
    /// Seconds. Missing for live streams.
    pub duration: Option<f64>,
    pub thumbnail: Option<String>,
    pub webpage_url: String,
    pub extractor: String,
    /// Only some extractors (YouTube) set it; `None` means they did not say.
    pub is_live: Option<bool>,
    pub formats: Vec<Format>,
    /// yt-dlp's `subtitles` and `automatic_captions`, read here and turned into
    /// `subtitle_languages` by `parse`.
    #[serde(skip_serializing)]
    subtitles: Option<BTreeMap<String, Vec<Track>>>,
    #[serde(skip_serializing)]
    automatic_captions: Option<BTreeMap<String, Vec<Track>>>,
    /// The languages the video has subtitles in, one entry per language.
    #[serde(skip_deserializing)]
    pub subtitle_languages: Vec<SubtitleLanguage>,
}

/// One subtitle file of a language; only its name matters here.
#[derive(Debug, Clone, PartialEq, Deserialize)]
struct Track {
    name: Option<String>,
}

/// A language the video offers subtitles in. `manual`: written by a person; `auto`: generated by
/// the site. Both can be true; yt-dlp prefers the manual ones. `name` is the site's name for it
/// (YouTube: "English"), which not every site gives.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SubtitleLanguage {
    pub code: String,
    pub name: Option<String>,
    pub manual: bool,
    pub auto: bool,
}

/// The pseudo-language of a live stream's chat replay, listed among the subtitles by YouTube. It
/// is a JSON feed, not text to embed.
const LIVE_CHAT: &str = "live_chat";

/// Manual and automatic tracks merged by language, in code order. A code that could not be
/// passed to `--sub-langs` (`is_language_code`) is left out, so every listed language can be
/// asked for.
fn languages(
    manual: Option<BTreeMap<String, Vec<Track>>>,
    auto: Option<BTreeMap<String, Vec<Track>>>,
) -> Vec<SubtitleLanguage> {
    let mut found: BTreeMap<String, SubtitleLanguage> = BTreeMap::new();
    for (tracks, is_auto) in [(manual, false), (auto, true)] {
        for (code, files) in tracks.into_iter().flatten() {
            if code == LIVE_CHAT || files.is_empty() || !is_language_code(&code) {
                continue;
            }
            let name = files.iter().find_map(|file| file.name.clone());
            let entry = found.entry(code.clone()).or_insert(SubtitleLanguage {
                code,
                name: None,
                manual: false,
                auto: false,
            });
            entry.name = entry.name.take().or(name);
            if is_auto {
                entry.auto = true;
            } else {
                entry.manual = true;
            }
        }
    }
    found.into_values().collect()
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all(serialize = "camelCase", deserialize = "snake_case"))]
pub struct Format {
    pub format_id: String,
    pub ext: String,
    /// The string `"none"` means the format has no video; `None` means yt-dlp does not know.
    /// Kept apart on purpose: the format picker needs both to classify formats.
    pub vcodec: Option<String>,
    /// Same convention as `vcodec`.
    pub acodec: Option<String>,
    // `f64` everywhere: yt-dlp mixes integers and decimals in the same field.
    pub height: Option<f64>,
    pub width: Option<f64>,
    pub fps: Option<f64>,
    /// Bitrates in kbit/s: total, audio, video.
    pub tbr: Option<f64>,
    pub abr: Option<f64>,
    pub vbr: Option<f64>,
    /// Bytes: exact, or yt-dlp's estimate when it has no exact size.
    pub filesize: Option<f64>,
    #[serde(skip_serializing)]
    filesize_approx: Option<f64>,
    pub format_note: Option<String>,
    pub protocol: Option<String>,
}

/// Only `_type`, read first so a playlist gets a clear error instead of a "missing field".
#[derive(Deserialize)]
struct Kind {
    #[serde(rename = "_type")]
    kind: Option<String>,
}

/// How long yt-dlp may take to answer before it is killed. A video takes ~3 s;
/// this only catches a server that never answers.
const TIMEOUT: Duration = Duration::from_secs(60);

fn args(url: &str, bin_dir: &Path, cookies: Option<&Cookies>) -> Vec<String> {
    let mut args = vec![
        "--dump-single-json".into(),
        // A `watch?v=...&list=...` link is the video, not its playlist.
        "--no-playlist".into(),
        // A playlist or channel link: list only its first entry, without resolving it, just to
        // read `_type` and fail fast. Resolving every entry took minutes. A single
        // video is unaffected.
        "--flat-playlist".into(),
        "--playlist-items".into(),
        "1".into(),
        "--js-runtimes".into(),
        js_runtime(bin_dir),
    ];
    // The browser cookies the user chose: a video that asks for a login fails to
    // analyse without them, long before the download.
    if let Some(cookies) = cookies {
        args.extend(cookies.args());
    }
    // Ends yt-dlp's options: whatever follows is a URL, never an option.
    args.extend(["--".into(), url.into()]);
    args
}

/// Runs yt-dlp and returns the metadata of the video at `url`. Gives up after `TIMEOUT`. A
/// playlist or channel link fails with `playlist`: list it with `playlist::fetch`.
pub async fn fetch(
    app: &AppHandle,
    url: &str,
    bin_dir: &Path,
    cookies: Option<&Cookies>,
) -> Result<Metadata, AppError> {
    check_url(url)?;
    parse(&run_json(app, args(url, bin_dir, cookies), TIMEOUT).await?)
}

/// Runs yt-dlp with `args` and returns what it printed to stdout (one JSON document). Kills its
/// process tree if it is still running after `timeout`. Shared with `playlist::fetch`.
pub(super) async fn run_json(
    app: &AppHandle,
    args: Vec<String>,
    timeout: Duration,
) -> Result<String, AppError> {
    let (run, mut events) = super::spawn(app, args)?;
    // Disarmed when this function returns and `_deadline` is dropped.
    let _deadline = run.cancel_after(timeout);
    let mut stdout = String::new();
    while let Some(event) = events.recv().await {
        match event {
            RunEvent::Stdout(line) => {
                stdout.push_str(&line);
                stdout.push('\n');
            }
            // The runner already puts stderr into the error of a failed run.
            RunEvent::Stderr(_) => {}
            RunEvent::Exited(result) => {
                result.map_err(|e| failure(e, timeout))?;
                return Ok(stdout);
            }
        }
    }
    Err(AppError::Unknown(
        "yt-dlp stopped without an exit code".into(),
    ))
}

/// The error of a failed run. Nothing but the time limit cancels an analysis, so a
/// cancellation means yt-dlp did not answer: `network`, like a timeout inside yt-dlp.
fn failure(error: AppError, timeout: Duration) -> AppError {
    match error {
        AppError::Cancelled(_) => AppError::Network(format!(
            "yt-dlp did not answer within {} s",
            timeout.as_secs()
        )),
        other => classify::refine(other),
    }
}

/// Whether the JSON is a playlist or channel (`_type`) instead of one video.
pub(super) fn is_playlist(json: &str) -> Result<bool, AppError> {
    let kind: Kind = serde_json::from_str(json).map_err(unreadable)?;
    Ok(matches!(
        kind.kind.as_deref(),
        Some("playlist" | "multi_video")
    ))
}

pub(super) fn unreadable(e: serde_json::Error) -> AppError {
    AppError::Unknown(format!("could not read yt-dlp's metadata: {e}"))
}

fn parse(json: &str) -> Result<Metadata, AppError> {
    if is_playlist(json)? {
        return Err(AppError::Playlist(
            "this URL is a playlist or channel, not one video".into(),
        ));
    }
    let mut metadata: Metadata = serde_json::from_str(json).map_err(unreadable)?;
    // `take()` moves the fallback out and leaves `None` in the hidden field.
    metadata.channel = metadata.channel.or(metadata.uploader.take());
    for format in &mut metadata.formats {
        format.filesize = format.filesize.or(format.filesize_approx.take());
    }
    metadata.subtitle_languages = languages(
        metadata.subtitles.take(),
        metadata.automatic_captions.take(),
    );
    sanitise(&mut metadata)?;
    Ok(metadata)
}

/// Most formats and subtitle languages kept. Real videos have dozens (YouTube: about 50 formats,
/// a few dozen languages); a hostile answer could list millions for the interface to walk through.
const MAX_FORMATS: usize = 2000;
const MAX_LANGUAGES: usize = 300;
/// The longest address of a video page accepted from a site (the queue refuses longer ones).
const MAX_PAGE_URL: usize = 8192;

/// Bounds and cleans what a site said about the video: see `text`. Only text and sizes
/// change; a normal video is left exactly as it was.
fn sanitise(m: &mut Metadata) -> Result<(), AppError> {
    if m.webpage_url.len() > MAX_PAGE_URL {
        return Err(AppError::Unknown(
            "could not read yt-dlp's metadata: the video address is too long".into(),
        ));
    }
    m.id = text::clean(&m.id, LABEL_MAX * 2);
    m.title = text::clean(&m.title, TITLE_MAX);
    if m.title.is_empty() {
        m.title = m.id.clone();
    }
    m.channel = text::clean_opt(m.channel.take(), NAME_MAX);
    m.extractor = text::clean(&m.extractor, LABEL_MAX);
    m.thumbnail = text::thumbnail(m.thumbnail.take());
    m.duration = m.duration.filter(|d| d.is_finite() && *d >= 0.0);
    m.formats.truncate(MAX_FORMATS);
    for f in &mut m.formats {
        f.format_id = text::clean(&f.format_id, LABEL_MAX);
        f.ext = text::clean(&f.ext, LABEL_MAX);
        for field in [
            &mut f.vcodec,
            &mut f.acodec,
            &mut f.format_note,
            &mut f.protocol,
        ] {
            *field = text::clean_opt(field.take(), LABEL_MAX);
        }
    }
    m.subtitle_languages.truncate(MAX_LANGUAGES);
    for language in &mut m.subtitle_languages {
        language.name = text::clean_opt(language.name.take(), LABEL_MAX);
    }
    Ok(())
}

