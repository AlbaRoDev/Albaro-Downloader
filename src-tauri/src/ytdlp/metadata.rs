    fn format<'a>(m: &'a Metadata, id: &str) -> &'a Format {
        m.formats.iter().find(|f| f.format_id == id).unwrap()
    }

    fn code_and_flags(m: &Metadata) -> Vec<(&str, Option<&str>, bool, bool)> {
        m.subtitle_languages
            .iter()
            .map(|l| (l.code.as_str(), l.name.as_deref(), l.manual, l.auto))
            .collect()
    }

    #[test]
